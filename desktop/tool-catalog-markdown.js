'use strict';

const CORE_TOOLS = Object.freeze([
  'exec_command', 'read_file', 'apply_patch', 'write_file', 'list_dir', 'directory_tree',
  'glob_file_search', 'search', 'run_tests', 'batch', 'project_status', 'git_status', 'git_diff'
]);

function inlineCode(value) {
  const marker = String.fromCharCode(96);
  return marker + String(value).replace(/[\r\n]/g, '').split(marker).join('') + marker;
}

function renderToolCatalogMarkdown(capabilityData) {
  const catalog = capabilityData && typeof capabilityData === 'object' ? capabilityData : {};
  const sourceTools = Array.isArray(catalog.tools) ? catalog.tools : [];
  const tools = new Map(sourceTools
    .filter(item => item && typeof item.name === 'string')
    .map(item => [item.name, item]));
  const groups = [
    ['Core coding workflow', name => CORE_TOOLS.includes(name)],
    ['Project and code intelligence', name => name.startsWith('project_') || name === 'game_project_intelligence'],
    ['Git and worktrees', name => name.startsWith('git_')],
    ['Agent collaboration', name => name.startsWith('task_') ||
      ['session_start', 'agent_status', 'send_agent_message', 'read_agent_messages', 'reply_to_agent_message'].includes(name)],
    ['Desktop, vision and audio', name => ['computer', 'tts'].includes(name)],
    ['Other registered tools', name => !CORE_TOOLS.includes(name) && !name.startsWith('project_') &&
      !name.startsWith('git_') && !name.startsWith('task_') &&
      !['session_start', 'agent_status', 'send_agent_message', 'read_agent_messages', 'reply_to_agent_message', 'computer', 'tts'].includes(name)]
  ];
  const sections = [];
  for (const [title, predicate] of groups) {
    const names = [...tools.keys()].filter(predicate).sort((a, b) => a.localeCompare(b));
    if (!names.length) continue;
    sections.push('## ' + title);
    for (const name of names) {
      const item = tools.get(name);
      sections.push('', '### ' + inlineCode(name), '',
        String(item.description || 'No description was published by the worker.').trim(),
        '',
        '- Permission mode: ' + String(item.mode || 'not specified'),
        '- Permission requirements: ' + String(item.permission_note || 'Not specified by the live catalog.'),
        '- Result contract: ' + String(item.returns || 'Not specified by the live catalog.'),
        '',
        'Argument schema:',
        '',
        '```json',
        JSON.stringify(item.parameters || { type: 'object', properties: {}, additionalProperties: false }, null, 2),
        '```');
    }
  }
  const toolCalling = catalog.tool_calling && typeof catalog.tool_calling === 'object' ? catalog.tool_calling : {};
  return [
    '# Windows Bridge tool reference',
    '',
    '> Generated from the registered Windows worker catalog. This file is regenerated by the app; do not edit it manually.',
    '',
    '- Catalog version: ' + String(catalog.catalog_version || 1),
    '- Registered tools: ' + tools.size,
    '- Transport contract: ' + String(toolCalling.mode || 'OneDrive mailbox'),
    '',
    '## General coding workflow',
    '',
    '**exec_command** is the language-neutral command entry point. Windows PowerShell is the host shell; invoke any interpreter, compiler, package manager, build system, test runner or executable installed on the Windows machine. Availability depends on the actual installed toolchains and PATH.',
    '',
    '1. Inspect the workspace and project instructions before editing.',
    '2. Use project/status and file-navigation tools to discover languages, toolchains, project structure and relevant source.',
    '3. Read complete relevant files or bounded pages before changing them.',
    '4. Make focused edits with the supported patch/write tools.',
    '5. Run project-native checks and tests, inspect exit codes and complete output, then verify the resulting diff.',
    '6. Batch independent operations; preserve dependencies and serialize conflicting writes.',
    '',
    '## Slash-style shortcuts',
    '',
    'These are ChatGPT-facing aliases, not additional registered tools or a separate command protocol. Resolve each alias to the existing OneDrive file or live Windows tool; the Windows app does not parse these slash forms.',
    '',
    '| Alias | Action |',
    '|---|---|',
    '| /help | Read AGENT.md and TOOLS.md. |',
    '| /status | Read STATUS.md. |',
    '| /tools | Read TOOLS.md. |',
    '| /screen | Read SCREEN.md and check its freshness. |',
    '| /agents | Invoke agent_status. |',
    '| /messages | Invoke read_agent_messages. |',
    '| /workspace | Invoke get_agent_context. |',
    '| /plan | Invoke update_plan. |',
    '| /tasks <project-id> | Invoke task_project_status and task_list with that ID. |',
    '| /inspect <path> | Invoke read_file for that workspace path. |',
    '| /test <command> | Invoke run_tests with the project-native command. |',
    '| /send <agent-id> <message> | Invoke send_agent_message using the exact catalog fields. |',
    '| /reply <message-id> <message> | Invoke reply_to_agent_message using the exact catalog fields. |',
    '',
    '## Batch and reference contract',
    '',
    String(toolCalling.rule || 'No batch contract was published by the worker.'),
    '',
    'Reference syntax: `' + String(toolCalling.reference_syntax || '{"$ref":"priorStepId.result.content"}') + '`',
    '',
    ...sections,
    ''
  ].join('\n');
}

module.exports = { CORE_TOOLS, renderToolCatalogMarkdown };
